plugins {
	java
	// Essential's Architectury Loom fork: the maintained Gradle toolchain for Forge 1.8.9
	// (RetroFuturaGradle, used by the 1.7.10 / 1.12.2 backports, does not cover 1.8.9).
	id("gg.essential.loom") version "1.15.50"
	// Forge 1.8.9 ships its binary patches pack200-compressed; Java 14+ dropped pack200.
	id("dev.architectury.architectury-pack200") version "0.1.3"
}

val modId = property("mod_id") as String
val modName = property("mod_name") as String
val modVersion = property("mod_version") as String
val minecraftVersion = property("minecraft_version") as String
version = modVersion
group = property("maven_group") as String
base {
	archivesName = "$modId-forge-$minecraftVersion"
}

// The mod targets Minecraft 1.8.9's Java 8 runtime.
java {
	toolchain.languageVersion = JavaLanguageVersion.of(8)
}

// ---------------------------------------------------------------------------------------
// Shared code from ../../mod, layered onto this project's own src/main/java (the Forge
// entrypoint and platform service):
//   - src/core/java          Minecraft-agnostic logic, Java 8 source shared with every target
//   - src/common/java        Minecraft-agnostic client glue that calls into the platform layer
//   - src/legacy-forge/java  the Forge client layer shared with the 1.7.10 / 1.12.2 backports,
//                            version-gated — resolved for 1.8.9 by legacy-preprocess.gradle
val peercraftDir = rootProject.file("../../mod")
sourceSets.main {
	java.srcDir(peercraftDir.resolve("src/core/java"))
	java.srcDir(peercraftDir.resolve("src/common/java"))
	resources.srcDir(peercraftDir.resolve("src/main/resources"))
	resources {
		// Pre-1.13 wants key=value .lang (generated by legacy-lang.gradle), not JSON.
		exclude("assets/peercraft/lang/*.json")
		// The modern (JAVA_21) mixin configs; this project ships peercraft.forge189.mixins.json.
		exclude("peercraft.mixins.json", "peercraft.client.mixins.json")
	}
}

repositories {
	maven("https://repo.spongepowered.org/maven/")
}

// Mixin itself is shaded into the jar: 1.8.9 has no shared Mixin loader mod.
val shade: Configuration by configurations.creating
configurations.implementation.get().extendsFrom(shade)

dependencies {
	minecraft("com.mojang:minecraft:$minecraftVersion")
	mappings("de.oceanlabs.mcp:mcp_stable:${property("mcp_mappings")}")
	forge("net.minecraftforge:forge:${property("forge_version")}")

	shade("org.spongepowered:mixin:${property("mixin_version")}") { isTransitive = false }
	annotationProcessor("org.spongepowered:mixin:0.8.5-SNAPSHOT")
	annotationProcessor("com.google.code.gson:gson:2.10.1")
	annotationProcessor("com.google.guava:guava:32.1.2-jre")
	annotationProcessor("org.ow2.asm:asm-tree:9.6")
	annotationProcessor("org.ow2.asm:asm-commons:9.6")
	annotationProcessor("org.ow2.asm:asm-util:9.6")
}

val mixinConfig = "peercraft.forge189.mixins.json"
loom {
	forge {
		pack200Provider.set(dev.architectury.pack200.java.Pack200Adapter())
		mixinConfig(mixinConfig)
	}
	@Suppress("UnstableApiUsage")
	mixin {
		defaultRefmapName.set("peercraft.mixins.refmap.json")
	}
	runs {
		named("client") {
			programArgs("--tweakClass", "org.spongepowered.asm.launch.MixinTweaker")
			property("mixin.debug", "true")
		}
	}
}

tasks.withType<JavaCompile>().configureEach {
	options.encoding = "UTF-8"
	// -Pjavac.maxerrs=N: see every error at once while working through the version gates.
	findProperty("javac.maxerrs")?.let { options.compilerArgs.addAll(listOf("-Xmaxerrs", it.toString())) }
}

tasks.processResources {
	inputs.property("mod_version", modVersion)
	filesMatching("mcmod.info") {
		expand("mod_version" to modVersion, "mod_id" to modId, "mod_name" to modName)
	}
}

tasks.jar {
	// Production (jar in mods/): FML runs the Mixin tweaker, which reads MixinConfigs. The FML mod
	// inside this jar must still be discovered, hence the two FMLCorePlugin* flags.
	manifest.attributes(
		"TweakClass" to "org.spongepowered.asm.launch.MixinTweaker",
		"TweakOrder" to "0",
		"MixinConfigs" to mixinConfig,
		"FMLCorePluginContainsFMLMod" to "true",
		"ForceLoadAsMod" to "true",
	)
	from(shade.map { zipTree(it) }) {
		exclude("META-INF/*.SF", "META-INF/*.RSA", "META-INF/*.DSA", "META-INF/MANIFEST.MF", "LICENSE.txt")
	}
	from(peercraftDir.resolve("../LICENSE")) { rename { "${it}_$modName" } }
}

apply(from = peercraftDir.resolve("gradle/modsync-helper.gradle"))
apply(from = peercraftDir.resolve("gradle/legacy-preprocess.gradle"))
apply(from = peercraftDir.resolve("gradle/legacy-lang.gradle"))
